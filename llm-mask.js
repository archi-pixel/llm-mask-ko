'use strict';
/**
 * llm-mask.js — LLM(OpenAI) 전송 «직전» 접수 원문 비식별 (순수 함수, 외부 의존 0)
 *
 * 배경/범위:
 *   - src/llm-shadow.js 의 maskPii 는 «저장용»(llm_shadow_logs.maskedText)이라 전송 경로와 무관하다.
 *     이 파일은 «전송용»이다. 둘은 목적이 달라 규칙도 다르다(여기선 호실 번호를 지우지 않는다 —
 *     호실은 분류 근거이고, 전송 상대는 위치를 알아야 건물/섹터를 맞춘다).
 *   - 규칙 엔진(intake-rules)·shadow 기록은 이 함수를 «거치지 않는다». 서버 내부 경로이기 때문이다.
 *
 * 설계 원칙 — 위양성(오탐)이 위음성보다 나쁘다:
 *   민원 본문에서 위치·증상 서술이 지워지면 분류가 틀리고, 틀린 분류는 곧바로 접수 품질로 드러난다.
 *   그래서 모든 규칙은 «확실할 때만» 지운다. 특히 이름은 호칭이 붙은 형태 + 흔한 성씨 화이트리스트일 때만 건드린다.
 *
 * 치환 순서(겹침 방지 — 순서를 바꾸면 오탐이 난다):
 *   1) 이메일   : 로컬파트에 숫자가 섞여도 통째로 지워야 도메인이 남지 않는다.
 *   2) 주민번호 : 13자리. 전화(9~12자리)보다 «먼저». 지금은 전화 규칙의 앞뒤 숫자 경계 덕에 순서를 바꿔도
 *               13자리를 못 건드리지만, 경계를 빼면 앞 9~12자리가 전화로 잘려 나가고 뒷자리가 남는다.
 *   3) 학번     : 20으로 시작하는 10자리.
 *   4) 전화     : 0으로 시작하는 9~12자리. 앞뒤 «숫자 경계»가 핵심 방어(호실·금액·연도·접수번호).
 *   5) 이름     : 위 치환 토큰([전화] 등)은 성씨 화이트리스트에 걸리지 않으므로 마지막이 안전하다.
 */

/** 치환 문자열 — 종류가 남아야 LLM 이 "연락처를 남겼다" 같은 문맥을 잃지 않는다. */
const REPLACEMENT = Object.freeze({
  phone: '[전화]',
  rrn: '[주민번호]',
  email: '[메일]',
  studentId: '[학번]',
  name: '[이름]',
});

// ── 1) 이메일 ────────────────────────────────────────────────────────────────
const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/g;

// ── 2) 주민등록번호 ──────────────────────────────────────────────────────────
//   앞뒤 숫자 경계로 더 긴 숫자열의 일부를 잘라내지 않는다.
const RRN_RE = /(?<![0-9])\d{6}-?[1-8]\d{6}(?![0-9])/g;

// ── 3) 학번(20으로 시작하는 10자리) ──────────────────────────────────────────
//   날짜 20260826(8자리)·접수번호 FR-20260826-001 은 숫자 런이 8자리라 걸리지 않는다.
const STUDENT_ID_RE = /(?<![0-9])20\d{8}(?![0-9])/g;

// ── 4) 전화(휴대·일반·안심번호) ──────────────────────────────────────────────
//   0으로 시작 + (2~4자리 국번/식별) + (3~4자리) + (4자리).
//   구분자는 하이픈·점·공백, 그리고 국내 사무실 번호 표기인 닫는 괄호("02)760-1234", "(02) 760-1234").
//   ★(?<![0-9]) 가 없으면 27501호·1500000원·20260826 안쪽의 0에서 매치가 시작돼 오탐이 난다.
//     앞자리는 «항상 2자리 이상»(0 뒤에 숫자가 반드시 온다)이라 "(0) 123 4567" 같은 것은 걸리지 않는다.
const PHONE_RE = /(?<![0-9])0\d{1,3}(?:\)[ \t]?|[-. \t])?\d{3,4}(?:\)[ \t]?|[-. \t])?\d{4}(?![0-9])/g;

// ── 5) 이름 + 호칭 ───────────────────────────────────────────────────────────
//   보수적 3중 잠금: ① 흔한 성씨로 시작 ② 전체 2~4자 ③ 호칭이 «반드시» 붙는다.
//   호칭 없는 맨 이름은 건드리지 않는다(사람 이름인지 판정할 근거가 없다).
const SURNAME_1 = '김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구';
const SURNAME_2 = '남궁|황보|제갈|사공|선우|독고';
// 호칭 — '님'은 선택(교수/교수님 둘 다), 단독 '님'·'씨'도 허용.
const TITLE = '(?:(?:교수|선생|박사|조교|연구원|주임|대리|과장|팀장|부장|처장|학생)님?|님|씨)';
// 호칭 뒤에 붙어도 되는 조사 — "김철수 교수님이", "홍길동님께" 를 놓치지 않기 위함.
//   조사가 아닌 한글이 이어지면(학생회관·학생증) 매치하지 않는다.
const PARTICLE = '께서|께|에게|한테|이라|라고|의|이|가|은|는|을|를|도|만|과|와|에'
  + '|입니다|입니|이고|이며|인데|이에요|예요|이십니다|이세요|이신|이라는';   // 서술격 어미 — "김철수 학생입니다" 를 놓치지 않기 위함

const NAME_RE = new RegExp(
  '(?<![가-힣])'
  + `((?:${SURNAME_2}|[${SURNAME_1}])[가-힣]{1,2})`   // 성(1~2자) + 이름(1~2자) = 2~4자
  + '([ ]?)'
  + `(${TITLE})`
  + `(?:(?![가-힣])|(?=${PARTICLE}))`,
  'g',
);

/** 이름 자리에 들어왔지만 사람 이름이 «아닌» 것이 확실한 낱말(성씨로 시작하는 일반명사). */
const NAME_STOPWORDS = new Set([
  '고객', '손님', '차장', '고등', '장애', '장학', '신입', '신고', '신청', '고장',
  '강의', '강의실', '강의동', '안전', '안내', '전기', '전산', '전체', '전화', '전공',
  '정보', '정문', '정기', '정수', '구매', '구내', '구역', '홍보', '차량', '주차', '주말',
  '오전', '오후', '오늘', '오늘날', '남녀', '이번', '이용', '이전', '최근', '최소', '최대',
  '문의', '문제', '성함', '하자', '하수', '노후', '배관', '배수', '조명', '조치',
  '유지', '유리', '임시', '한국', '서류', '백만', '심야', '양호', '허가', '우천',
  '권한', '황사', '박스', '송풍', '윤활',
]);
/** 이름이 직함으로 «끝나면»(또는 직함 그 자체이면) 사람 이름이 아니다:
 *  정교수님·정부장학생·주임님(주+임으로 오분해)·박사님 …. */
const TITLE_TAILS = [
  '교수', '선생', '박사', '조교', '연구원', '주임', '대리', '과장', '팀장', '부장', '처장',
  '학생', '차장', '실장', '원장', '소장', '국장', '사장', '이사', '기사', '여사',
];

function looksLikePersonName(name) {
  if (NAME_STOPWORDS.has(name)) return false;
  for (const tail of TITLE_TAILS) {
    if (name.endsWith(tail)) return false;
  }
  return true;
}

function emptyHits() {
  return { phone: 0, rrn: 0, email: 0, studentId: 0, name: 0 };
}

/**
 * LLM 전송용 비식별. 원문은 반환값 어디에도 담기지 않는다(치환 «건수»만 집계).
 *
 * @param {string} text 접수 원문
 * @returns {{ text: string, hits: { phone:number, rrn:number, email:number, studentId:number, name:number } }}
 */
function maskForLlm(text) {
  const hits = emptyHits();
  if (text === null || text === undefined) return { text: '', hits };
  let out = typeof text === 'string' ? text : String(text);
  if (out === '') return { text: '', hits };

  out = out.replace(EMAIL_RE, () => { hits.email += 1; return REPLACEMENT.email; });
  out = out.replace(RRN_RE, () => { hits.rrn += 1; return REPLACEMENT.rrn; });
  out = out.replace(STUDENT_ID_RE, () => { hits.studentId += 1; return REPLACEMENT.studentId; });
  out = out.replace(PHONE_RE, () => { hits.phone += 1; return REPLACEMENT.phone; });
  out = out.replace(NAME_RE, (m, name, sep, title) => {
    if (!looksLikePersonName(name)) return m;
    hits.name += 1;
    return REPLACEMENT.name + sep + title;
  });

  return { text: out, hits };
}

/** 치환 총 건수(엔벨로프 meta.piiMasked 용). */
function totalHits(hits) {
  if (!hits) return 0;
  return (hits.phone || 0) + (hits.rrn || 0) + (hits.email || 0) + (hits.studentId || 0) + (hits.name || 0);
}

module.exports = {
  maskForLlm,
  totalHits,
  REPLACEMENT,
  // 운영 중 오탐이 보고되면 여기를 늘린다(정규식 수정보다 안전하다).
  NAME_STOPWORDS,
};
